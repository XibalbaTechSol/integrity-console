import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

// Regenerates src/chain/bytecode.ts from an integrity-core SovereignAgent artifact.
//
//   npm run sync-chain-bytecode -- <SovereignAgent.json> [source-label]
//
// <SovereignAgent.json> is either a Foundry artifact (contracts/out/SovereignAgent.sol/
// SovereignAgent.json, `bytecode.object`) or the SDK's shipped copy
// (integrity-sdk/integrity_sdk/abis/SovereignAgent.json, `bytecode` string), which
// integrity-core CI keeps byte-identical to a fresh build (`scripts/sync_abis.py --check`).
// Take it from integrity-core's main, e.g.
//   git -C <core> show origin/main:integrity-sdk/integrity_sdk/abis/SovereignAgent.json > sa.json
// v3 has no per-agent StateAnchor (ActionAnchor is a singleton), so only SovereignAgent is emitted.

const [artifactArg, label] = process.argv.slice(2);
if (!artifactArg) {
  console.error('usage: sync-chain-bytecode <SovereignAgent.json> [source-label]');
  process.exit(2);
}
const dashboardRoot = resolve(import.meta.dirname, '..');
const artifact = JSON.parse(await readFile(resolve(artifactArg), 'utf8'));
const bytecode = typeof artifact.bytecode === 'string' ? artifact.bytecode : artifact.bytecode?.object;
if (typeof bytecode !== 'string' || !bytecode.startsWith('0x')) {
  throw new Error(`${artifactArg} has no deployable bytecode`);
}
const ctor = artifact.abi.find((i) => i.type === 'constructor');
const ctorArgs = ctor?.inputs.map((i) => i.name).join(', ');
if (ctorArgs !== 'did_, controller_, registry_') {
  throw new Error(`unexpected SovereignAgent constructor (${ctorArgs}); is this artifact from current integrity-core main?`);
}

const lines = [
  `// Generated by \`npm run sync-chain-bytecode\` from integrity-core${label ? ` ${label}` : ''}.`,
  '// Do not hand-edit. Constructor: SovereignAgent(did_, controller_, registry_).',
  '',
  `export const SOVEREIGN_AGENT_BYTECODE = ${JSON.stringify(bytecode)} as const;`,
  `export const SOVEREIGN_AGENT_ABI = ${JSON.stringify(artifact.abi)} as const;`,
];
await writeFile(resolve(dashboardRoot, 'src', 'chain', 'bytecode.ts'), `${lines.join('\n')}\n`);
